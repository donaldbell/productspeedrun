#!/usr/bin/env python3
"""Generate include/pins.h from the board's design.py, so the firmware and the board can't disagree.

Runs ../5-electronics/src/design.py against a stub of tools/kicad's schkit (no KiCad needed), finds the
ESP32-C3-WROOM-02 module, maps its pins to GPIO numbers and writes one PIN_<NET> per signal net.
It also writes what the board does to each pin (pull-ups / pull-downs and what else is on the net) and
the battery-sense divider ratio, so main code can check its assumptions with #if / static_assert.

Usage: python3 scripts/gen_pins.py [--check]     (also run before every build by scripts/pio_pins.py)
"""
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
DESIGN = os.path.normpath(os.path.join(FW, "..", "5-electronics", "src", "design.py"))
OUT = os.path.join(FW, "include", "pins.h")

# ESP32-C3-WROOM-02 module pin -> GPIO (datasheet v1.x, table "Pin Definitions"). Power pins are left out.
WROOM02_GPIO = {"3": 4, "4": 5, "5": 6, "6": 7, "7": 8, "8": 9, "10": 10, "11": 20, "12": 21,
                "13": 18, "14": 19, "15": 3, "16": 2, "17": 1, "18": 0}
POWER_NETS = {"3V3", "GND", "EN"}
STRAPS = {2, 8, 9}
DEEP_SLEEP_WAKE = set(range(0, 6))      # ESP32-C3: only GPIO0-5 can wake it from deep sleep


def load_design(path):
    """Execute design.py with stub schkit / parts modules and return its PARTS dict."""
    parts = {}

    def part(ref, lib_id, value, fp, lcsc, mpn, at, nets, desc="", **extra):
        parts[ref] = dict(lib_id=lib_id, value=value, nets=nets, desc=desc, **extra)

    def two_pin(lib_id):
        return lambda ref, value, at, a, b: part(ref, lib_id, value, "", "", "", at, {"1": a, "2": b})

    schkit = types.ModuleType("schkit")
    names = dict(setup=lambda *a, **k: None, part=part, cap=two_pin("Device:C"), res=two_pin("Device:R"),
                 at=lambda c, r: (c, r), box_symbol=lambda *a, **k: None, gnd_pins=lambda *n: {x: "GND" for x in n},
                 NOTES=[], OFF_BOARD=[], PARTS=parts, FP_0603C="", FP_0805C="", FP_0603R="", CAPS={}, RES={}, G=2.54)
    schkit.__dict__.update(names)
    schkit.__all__ = list(names)
    stub_parts = types.ModuleType("parts")
    stub_parts.__getattr__ = lambda name: (lambda *a, **k: "stub:" + name)
    saved = {k: sys.modules.get(k) for k in ("schkit", "parts")}
    sys.modules.update(schkit=schkit, parts=stub_parts)
    try:
        with open(path) as f:
            exec(compile(f.read(), path, "exec"), {"__name__": "design", "__file__": path})
    finally:
        for k, v in saved.items():
            if v is None:
                sys.modules.pop(k, None)
            else:
                sys.modules[k] = v
    return parts


def ohms(value):
    v = value.strip().upper().replace("Ω", "").replace("R", "")
    mult = {"K": 1e3, "M": 1e6}.get(v[-1:], 1)
    return float(v[:-1] if mult != 1 else v) * mult


def generate(design_path=DESIGN):
    parts = load_design(design_path)
    mods = [r for r, p in parts.items() if p["lib_id"] == "RF_Module:ESP32-C3-WROOM-02"]
    if len(mods) != 1:
        raise SystemExit("gen_pins: expected one ESP32-C3-WROOM-02 in design.py, found %r" % mods)
    mcu = mods[0]

    pins = []           # (net, gpio)
    for pin, net in parts[mcu]["nets"].items():
        if net and net not in POWER_NETS and pin in WROOM02_GPIO:
            pins.append((net, WROOM02_GPIO[pin]))
    pins.sort(key=lambda t: t[1])

    def on_net(net):
        """Everything else on a net: (ref, pin, part) for each connection."""
        return [(r, pn, p) for r, p in sorted(parts.items()) if r != mcu
                for pn, n in p["nets"].items() if n == net]

    rel = os.path.relpath(design_path, FW)
    out = ["// GENERATED by scripts/gen_pins.py from %s. Do not edit: change the board, then rebuild." % rel,
           "// Every PIN_* can be overridden with a build flag (-DPIN_RGB_DATA=8 for a plain ESP32-C3 dev board).",
           "#pragma once", "", "#define BOARD_NAME \"%s\"" % "Backpack Defender Rev B", ""]
    for net, gpio in pins:
        pull_up = pull_dn = None
        others = []
        for ref, pn, p in on_net(net):
            if p["lib_id"] == "Device:R":
                other = [n for k, n in p["nets"].items() if k != pn][0]
                if other == "3V3":
                    pull_up = (ref, p["value"])
                    continue
                if other == "GND":
                    pull_dn = (ref, p["value"])
                    continue
            others.append("%s.%s" % (ref, pn))
        notes = []
        if pull_up:
            notes.append("pull-up %s %s" % pull_up)
        if pull_dn:
            notes.append("pull-down %s %s" % pull_dn)
        if others:
            notes.append("to " + ", ".join(others))
        if gpio in STRAPS:
            notes.append("strapping pin")
        if gpio in DEEP_SLEEP_WAKE:
            notes.append("can wake from deep sleep")
        name = "PIN_" + net
        out += ["// %s: %s" % (net, "; ".join(notes) or "no other connections"),
                "#ifndef %s" % name, "#define %s %d" % (name, gpio), "#endif",
                "#define %s_PULLUP %d" % (name, 1 if pull_up else 0),
                "#define %s_PULLDOWN %d" % (name, 1 if pull_dn else 0), ""]

    # Battery sense divider: resistor VBAT-VBAT_SENSE over resistor VBAT_SENSE-GND
    top = [p for p in parts.values() if p["lib_id"] == "Device:R" and set(p["nets"].values()) == {"VBAT", "VBAT_SENSE"}]
    bot = [p for p in parts.values() if p["lib_id"] == "Device:R" and set(p["nets"].values()) == {"VBAT_SENSE", "GND"}]
    if len(top) == 1 and len(bot) == 1:
        rt, rb = ohms(top[0]["value"]), ohms(bot[0]["value"])
        out += ["// VBAT_SENSE = VBAT x %g / (%g + %g): multiply the pin voltage by this to get VBAT" % (rb, rt, rb),
                "#define VBAT_SENSE_RATIO %.4ff" % ((rt + rb) / rb), ""]
    return "\n".join(out)


def main():
    text = generate()
    old = open(OUT).read() if os.path.exists(OUT) else None
    if "--check" in sys.argv:
        sys.exit(0 if old == text else "include/pins.h is out of date: run scripts/gen_pins.py")
    if old != text:            # only touch the file when it changes, so builds stay incremental
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print("gen_pins: wrote", os.path.relpath(OUT, FW))


if __name__ == "__main__":
    main()
