#!/usr/bin/env python3
"""Generate src/sound_data.h: every alarm sound and system chirp as a Standard MIDI File in flash.

The alarm sounds are the hosts' picks from Phil Burk's Mobileer ringtones (sounds/mobileer/*.mid,
Apache-2.0, see lib/mobileer/NOTICE). The four system chirps are short MIDI files written here into
sounds/system/, so everything plays through the same Mobileer engine and test/render_sounds.sh hears
exactly what the device will.

Usage: python3 scripts/gen_sounds.py [--check]     (also run before every build by scripts/pio_pre.py)
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
OUT = os.path.join(FW, "src", "sound_data.h")

# key (stored in NVS), name on the settings page, family, emoji, file, engine volume. The first one is
# the default. Volume is the engine's master volume (128 = as authored), set so each sound peaks near
# 28000 of 32767 before the kid's volume step: test/render_sounds.sh prints a suggestion for each.
ALARMS = [
    ("ringandting", "Ring and Ting", "Rings", "🔔", "mobileer/RingAndTing_rt.mid", 1320),
    ("fiverecho", "Fiver Echo", "Rings", "📣", "mobileer/FiverEcho.mid", 270),
    ("steeldrum", "Steel Drum", "Rings", "🥁", "mobileer/Tremolo1_SteelDrum.mid", 870),
    ("upanddown", "Up and Down", "Songs", "🎢", "mobileer/UpAndDown_rt.mid", 380),
    ("echoecho", "Echo Echo", "Songs", "🏔️", "mobileer/EchoEcho_rt.mid", 790),
    ("furelise", "Für Elise", "Songs", "🎹", "mobileer/FurElise_rt.mid", 620),
]

# System chirps: General MIDI program (0-based), engine volume, then (note, ms, velocity); note 0 = rest.
GLOCKENSPIEL, MARIMBA, OBOE = 9, 12, 68
CHIRPS = [
    ("awake", GLOCKENSPIEL, 690, [(84, 90, 100), (91, 200, 100)]),               # C6 G6: "I'm awake"
    ("sad", OBOE, 2300, [(79, 300, 115), (75, 300, 110), (72, 600, 105)]),        # G5 Eb5 C5: tired
    ("silenced", MARIMBA, 710, [(88, 80, 100), (81, 140, 90)]),                  # E6 A5: shh
    ("saved", GLOCKENSPIEL, 430, [(84, 90, 100), (88, 90, 100), (91, 90, 100), (96, 300, 110)]),  # C E G C
]

PPQ = 480
TEMPO_US = 500000                                  # 120 bpm: one tick = 500000 / 480 us


def varlen(n):
    out = [n & 0x7F]
    n >>= 7
    while n:
        out.insert(0, 0x80 | (n & 0x7F))
        n >>= 7
    return bytes(out)


def chirp_midi(program, notes):
    """A type-0 Standard MIDI File: tempo, program change on channel 0, then the notes in a row."""
    ticks = lambda ms: round(ms * 1000 * PPQ / TEMPO_US)
    trk = b"\x00\xFF\x51\x03" + TEMPO_US.to_bytes(3, "big") + b"\x00" + bytes([0xC0, program])
    gap = 0
    for note, ms, vel in notes:
        if not note:
            gap += ticks(ms)
            continue
        trk += varlen(gap) + bytes([0x90, note, vel]) + varlen(ticks(ms)) + bytes([0x80, note, 0])
        gap = 0
    trk += varlen(gap) + b"\xFF\x2F\x00"
    return b"MThd" + struct.pack(">IHHH", 6, 0, 1, PPQ) + b"MTrk" + struct.pack(">I", len(trk)) + trk


def c_array(name, data):
    lines = ["static const uint8_t %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    return lines


def generate():
    sounds = os.path.join(FW, "sounds")
    os.makedirs(os.path.join(sounds, "system"), exist_ok=True)
    chirp_files = []
    for key, program, volume, notes in CHIRPS:
        rel = "system/%s.mid" % key
        data = chirp_midi(program, notes)
        path = os.path.join(sounds, rel)
        if not os.path.exists(path) or open(path, "rb").read() != data:
            with open(path, "wb") as f:
                f.write(data)
        chirp_files.append((key, rel, volume))

    out = ["// GENERATED by scripts/gen_sounds.py from sounds/*.mid. Do not edit: change the script, then rebuild.",
           "// Alarm sounds: Phil Burk's Mobileer ringtones (Apache-2.0, lib/mobileer/NOTICE). Chirps: ours.",
           "#pragma once", "#include <stdint.h>", ""]
    for key, _, _, _, rel, _ in ALARMS:
        out += ["// sounds/" + rel] + c_array("MID_" + key, open(os.path.join(sounds, rel), "rb").read()) + [""]
    for key, rel, _ in chirp_files:
        out += ["// sounds/" + rel] + c_array("MID_SYS_" + key, open(os.path.join(sounds, rel), "rb").read()) + [""]
    out.append("#define SOUND_TABLE \\")
    for key, name, family, emoji, _, volume in ALARMS:
        out.append('  {"%s", "%s", "%s", "%s", {MID_%s, sizeof(MID_%s), %d}}, \\' % (key, name, family, emoji, key, key, volume))
    out += ["", "#define SYSTEM_TABLE \\"]
    for key, _, volume in chirp_files:
        out.append("  {MID_SYS_%s, sizeof(MID_SYS_%s), %d}, \\" % (key, key, volume))
    out.append("")
    return "\n".join(out) + "\n"


def main():
    text = generate()
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in sys.argv:
        sys.exit(0 if old == text else "src/sound_data.h is out of date: run scripts/gen_sounds.py")
    if old != text:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("gen_sounds: wrote", os.path.relpath(OUT, FW))


if __name__ == "__main__":
    main()
